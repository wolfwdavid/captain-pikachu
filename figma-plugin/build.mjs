// Generates code.js for the Figma plugin with the same artwork the web app uses.
// Run: npm run figma   (then Figma desktop → Plugins → Development → Import plugin from manifest…)
import { writeFileSync } from "node:fs";
import { svg, svgSide, svgBack } from "../src/artwork.js";

const art = { front: svg, side: svgSide, back: svgBack };
const code = `// generated by figma-plugin/build.mjs — do not edit
const ART = ${JSON.stringify(art)};
const LIVE = "https://wolfwdavid.github.io/captain-pikachu/";

figma.showUI(__html__, { width: 260, height: 250 });

function place(names) {
  const c = figma.viewport.center, nodes = [];
  names.forEach((name, i) => {
    const n = figma.createNodeFromSvg(ART[name]);
    n.name = "Captain Pikachu — " + name;
    n.resize(512, 512);
    n.x = Math.round(c.x - (names.length * 552) / 2 + i * 552); n.y = Math.round(c.y - 256);
    figma.currentPage.appendChild(n); nodes.push(n);
  });
  figma.currentPage.selection = nodes; figma.viewport.scrollAndZoomIntoView(nodes);
  figma.notify("Pika pika! ⚡");
}

figma.ui.onmessage = (msg) => {
  if (msg.type === "insert") place(msg.names);
  if (msg.type === "live") figma.openExternal(LIVE);
};
`;
writeFileSync(new URL("./code.js", import.meta.url), code);
console.log("figma-plugin/code.js written");
